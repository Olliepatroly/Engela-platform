function MuscleShape({
  def,
  figure,
  kind,
}: {
  def: MuscleDef;
  figure: Figure;
  kind: "primary" | "secondary" | null;
}) {
  const cls = `${styles.muscle} ${kind === "primary" ? styles.primary : ""} ${
    kind === "secondary" ? styles.secondary : ""
  }`;
  if (def.sym) {
    return (
      <g className={cls}>
        <title>{MUSCLE_LABELS[def.muscle]}</title>
        <path d={symPath(def.shape.start, def.shape.segs, figure)} />
      </g>
    );
  }
  const m = mirrored(def.shape.start, def.shape.segs);
  return (
    <g className={cls}>
      <title>{MUSCLE_LABELS[def.muscle]}</title>
      <path d={pathFrom(def.shape.start, def.shape.segs, figure, true)} />
      <path d={pathFrom(m.start, m.segs, figure, true)} />
    </g>
  );
}

function FigureView({
  view,
  figure,
  primary,
  secondary,
}: {
  view: View;
  figure: Figure;
  primary: Set<MuscleGroup>;
  secondary: Set<MuscleGroup>;
}) {
  const muscles = view === "front" ? FRONT_MUSCLES : BACK_MUSCLES;
  const details = view === "front" ? FRONT_DETAILS : BACK_DETAILS;

  return (
    <figure className={styles.figure}>
      <svg viewBox="0 0 300 640" role="img" aria-label={`${view} view of the body`}>
        <path className={styles.body} d={symPath(OUTLINE_START, OUTLINE, figure)} />
        {view === "back" ? (
          <path className={styles.hair} d={symPath(HAIR_BACK.start, HAIR_BACK.segs, figure)} />
        ) : null}
        {muscles.map((def) => (
          <MuscleShape
            key={`${def.muscle}-${view}`}
            def={def}
            figure={figure}
            kind={
              primary.has(def.muscle)
                ? "primary"
                : secondary.has(def.muscle)
                  ? "secondary"
                  : null
            }
          />
        ))}
        {details.map((d, i) => (
          <g key={i} className={styles.detail}>
            <path d={pathFrom(d.start, d.segs, figure, false)} />
            {d.paired ? (
              <path
                d={pathFrom(mirrored(d.start, d.segs).start, mirrored(d.start, d.segs).segs, figure, false)}
              />
            ) : null}
          </g>
        ))}
      </svg>
      <figcaption className={styles.viewLabel}>{view === "front" ? "Front" : "Back"}</figcaption>
    </figure>
  );
}

/**
 * Muscles-worked body map (front and back views, male or female figure).
 * Every compartment is drawn as anatomical line art; the ones this session
 * works are filled (amber = worked directly, slate = also involved). Status
 * rule applies here too: the legend always names the groups in text.
 */
export function BodyMap({
  primary,
  secondary = [],
  figure = "male",
}: {
  primary: MuscleGroup[];
  secondary?: MuscleGroup[];
  figure?: Figure;
}) {
  const primarySet = new Set(primary);
  // A muscle that is primary anywhere in the session shows as primary.
  const secondarySet = new Set(secondary.filter((m) => !primarySet.has(m)));
  const names = (set: Set<MuscleGroup>) =>
    Array.from(set)
      .map((m) => MUSCLE_LABELS[m])
      .join(", ");

  return (
    <div className={styles.wrap}>
      <div className={styles.figures}>
        <FigureView view="front" figure={figure} primary={primarySet} secondary={secondarySet} />
        <FigureView view="back" figure={figure} primary={primarySet} secondary={secondarySet} />
      </div>
      <dl className={styles.legend}>
        {primarySet.size > 0 ? (
          <div className={styles.legendRow}>
            <dt className={styles.legendTerm}>
              <span className={`${styles.legendDot} ${styles.legendDotPrimary}`} aria-hidden="true" />
              Worked directly
            </dt>
            <dd className={styles.legendNames}>{names(primarySet)}</dd>
          </div>
        ) : null}
        {secondarySet.size > 0 ? (
          <div className={styles.legendRow}>
            <dt className={styles.legendTerm}>
              <span
                className={`${styles.legendDot} ${styles.legendDotSecondary}`}
                aria-hidden="true"
              />
              Also involved
            </dt>
            <dd className={styles.legendNames}>{names(secondarySet)}</dd>
          </div>
        ) : null}
        {primarySet.size === 0 && secondarySet.size === 0 ? (
          <p className={styles.legendEmpty}>No muscle groups highlighted.</p>
        ) : null}
      </dl>
    </div>
  );
}
