type Figure = "male" | "female";
type View = "front" | "back";

/* ── Geometry ─────────────────────────────────────────────────────────
 * Both figures are authored once as cubic bezier paths on a 300 × 640
 * canvas (centre line x = 150) for the male frame. The female frame is
 * the same drawing passed through a piecewise horizontal scale around
 * the centre line: narrower shoulders and waist, wider hips. */

type Pt = readonly [number, number];
type Seg = { c1: Pt; c2: Pt; to: Pt };

const CX = 150;

/** seg(c1x, c1y, c2x, c2y, x, y) — one cubic segment. */
function seg(c1x: number, c1y: number, c2x: number, c2y: number, x: number, y: number): Seg {
  return { c1: [c1x, c1y], c2: [c2x, c2y], to: [x, y] };
}

/* Horizontal scale by height for the female frame (1 = male width). */
const FEMALE_STOPS: readonly Pt[] = [
  [0, 1],
  [70, 1],
  [115, 0.9],
  [200, 0.88],
  [270, 0.85],
  [310, 0.96],
  [350, 1.07],
  [405, 1.05],
  [475, 1],
  [640, 0.96],
];

function scaleAt(y: number, figure: Figure): number {
  if (figure === "male") return 1;
  const stops = FEMALE_STOPS;
  if (y <= stops[0]![1]) return stops[0]![1];
  for (let i = 1; i < stops.length; i += 1) {
    const [y1, s1] = stops[i]!;
    const [y0, s0] = stops[i - 1]!;
    if (y <= y1) return s0 + ((y - y0) / (y1 - y0)) * (s1 - s0);
  }
  return stops[stops.length - 1]![1];
}

function tx(p: Pt, figure: Figure): Pt {
  return [CX + (p[0] - CX) * scaleAt(p[1], figure), p[1]];
}

function mir(p: Pt): Pt {
  return [2 * CX - p[0], p[1]];
}

function fmt(p: Pt): string {
  return `${p[0].toFixed(1)} ${p[1].toFixed(1)}`;
}

/** A plain path from authored points, shaped for the figure. */
function pathFrom(start: Pt, segs: Seg[], figure: Figure, close: boolean): string {
  const t = (p: Pt) => tx(p, figure);
  let d = `M ${fmt(t(start))}`;
  for (const s of segs) d += ` C ${fmt(t(s.c1))} ${fmt(t(s.c2))} ${fmt(t(s.to))}`;
  return close ? `${d} Z` : d;
}

/** The same shape mirrored to the other side of the body. */
function mirrored(start: Pt, segs: Seg[]): { start: Pt; segs: Seg[] } {
  return {
    start: mir(start),
    segs: segs.map((s) => ({ c1: mir(s.c1), c2: mir(s.c2), to: mir(s.to) })),
  };
}

/** Symmetric closed path: author the left half from a centre-line start to a
 * centre-line end; the right half is generated by mirroring back. */
function symPath(start: Pt, segs: Seg[], figure: Figure): string {
  const t = (p: Pt) => tx(p, figure);
  let d = `M ${fmt(t(start))}`;
  for (const s of segs) d += ` C ${fmt(t(s.c1))} ${fmt(t(s.c2))} ${fmt(t(s.to))}`;
  const anchors: Pt[] = [start, ...segs.map((s) => s.to)];
  for (let i = segs.length - 1; i >= 0; i -= 1) {
    const s = segs[i]!;
    d += ` C ${fmt(t(mir(s.c2)))} ${fmt(t(mir(s.c1)))} ${fmt(t(mir(anchors[i]!)))}`;
  }
  return `${d} Z`;
}

